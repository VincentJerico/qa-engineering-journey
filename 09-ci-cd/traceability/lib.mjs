// Requirements traceability: manual test cases (the "requirements" of this repo) against the
// automated tests that cover them. Pure functions only; trace.mjs does the file and process work.

export const PRIORITY_TAGS = ['@high', '@medium', '@low'];

export const CASE_ID = /(?:TC|SC)-[A-Z0-9]+(?:-[A-Z0-9]+)*-\d{3}/;

/**
 * Cases from one manual test-case document. A case is a heading like
 * `### TC-CHK-001 — Complete checkout happy path`, optionally followed by a `**Priority:** High` line.
 */
export function parseCases(markdown, doc) {
  const cases = [];
  const lines = markdown.split('\n');
  lines.forEach((line, i) => {
    const m = line.match(new RegExp(`^###\\s+(${CASE_ID.source})\\s+—\\s+(.+?)\\s*$`));
    if (!m) return;
    const priority = lines[i + 1]?.match(/\*\*Priority:\*\*\s*([A-Za-z]+)/)?.[1];
    cases.push({ id: m[1], title: m[2], priority, doc, anchor: githubAnchor(line.replace(/^###\s+/, '')) });
  });
  return cases;
}

/** The anchor GitHub generates for a Markdown heading. */
export function githubAnchor(heading) {
  return heading
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N} _-]/gu, '')
    .replace(/ /g, '-');
}

/**
 * Tests from `playwright test --list --reporter=json`. `suite` names the suite ("UI", "API") and
 * `dir` is the suite folder relative to the repo root, used to build links. Setup steps
 * (`*.setup.ts`, e.g. saving a login session) are fixtures, not test cases, so they're skipped.
 */
export function collectTests(listJson, { suite, dir }) {
  const tests = [];
  const walk = (node) => {
    for (const spec of node.specs ?? []) {
      if (/\.setup\.[cm]?[jt]s$/.test(spec.file)) continue;
      for (const t of spec.tests) {
        tests.push({
          title: spec.title,
          id: spec.title.match(new RegExp(`^(${CASE_ID.source}):`))?.[1] ?? null,
          file: `${dir}/tests/${spec.file}`,
          project: t.projectName || suite,
          suite,
          tags: (spec.tags ?? []).map((tag) => `@${tag.replace(/^@/, '')}`), // the JSON reporter drops the @
        });
      }
    }
    for (const child of node.suites ?? []) walk(child);
  };
  for (const s of listJson.suites ?? []) walk(s);
  return tests;
}

/**
 * Checks the rules and builds one row per case.
 *  1. Every automated test title starts with a case ID ("TC-CHK-001: ...").
 *  2. Every ID a test uses exists in the manual docs.
 *  3. Every case is automated, unless manualOnly lists it with a reason.
 *  4. Case IDs are unique across the manual docs.
 *  5. manualOnly only lists cases that exist and really have no test.
 *  6. Every test carries exactly one priority tag, and it matches its case (`@high` for High).
 */
export function check({ cases, tests, manualOnly = {} }) {
  const problems = [];
  const byId = new Map();
  for (const c of cases) {
    if (byId.has(c.id)) problems.push(`duplicate case ID ${c.id} in ${byId.get(c.id).doc} and ${c.doc}`);
    else byId.set(c.id, c);
  }
  for (const t of tests) {
    if (!t.id) problems.push(`untraced test: "${t.title}" (${t.file}) does not start with a case ID`);
    else if (!byId.has(t.id)) problems.push(`unknown case: "${t.title}" (${t.file}) uses ${t.id}, which no manual doc defines`);
    else {
      const want = byId.get(t.id).priority ? `@${byId.get(t.id).priority.toLowerCase()}` : undefined;
      const have = (t.tags ?? []).filter((tag) => PRIORITY_TAGS.includes(tag));
      if (!want) problems.push(`no priority: ${t.id} (${byId.get(t.id).doc}) has no **Priority:** line to tag from`);
      else if (have.length !== 1 || have[0] !== want) {
        problems.push(`priority tag mismatch: "${t.title}" (${t.file}) has [${have.join(', ')}], its case says ${want}`);
      }
    }
  }
  const testsById = Map.groupBy(tests.filter((t) => t.id), (t) => t.id);
  for (const [id, reason] of Object.entries(manualOnly)) {
    if (!byId.has(id)) problems.push(`manual-only lists ${id}, which no manual doc defines`);
    else if (testsById.has(id)) problems.push(`manual-only lists ${id}, but it is automated; remove it from the list`);
    else if (!reason?.trim()) problems.push(`manual-only lists ${id} without a reason`);
  }
  const rows = [...byId.values()].map((c) => {
    const covering = testsById.get(c.id) ?? [];
    if (covering.length === 0 && !(c.id in manualOnly)) {
      problems.push(`not automated: ${c.id} (${c.doc}) has no test and is not listed as manual-only`);
    }
    return { ...c, tests: covering, manualOnly: manualOnly[c.id] };
  });
  return { problems, rows };
}

/** TRACEABILITY.md content. Deterministic, so `--check` can compare it byte for byte. */
export function render(rows) {
  const docs = Map.groupBy(rows, (r) => r.doc);
  const automated = rows.filter((r) => r.tests.length > 0).length;
  const out = [
    '# Traceability matrix',
    '',
    '<!-- Generated by 09-ci-cd/traceability/trace.mjs --update. Do not edit by hand; CI fails if it is stale. -->',
    '',
    'Every manual test case, and the automated test that covers it. CI regenerates this file from the',
    'case documents and the test list Playwright reports, and fails if a test has no case, points at a',
    "case that doesn't exist, or a case loses its test. See [09-ci-cd/traceability](09-ci-cd/traceability/).",
    '',
    '## Summary',
    '',
    '| Document | Cases | Automated | Manual only |',
    '| --- | --: | --: | --: |',
  ];
  for (const [doc, list] of docs) {
    const auto = list.filter((r) => r.tests.length > 0).length;
    out.push(`| [${doc.split('/').pop()}](${doc}) | ${list.length} | ${auto} | ${list.length - auto} |`);
  }
  out.push(`| **Total** | **${rows.length}** | **${automated}** | **${rows.length - automated}** |`, '');
  const byPriority = Map.groupBy(rows, (r) => r.priority ?? 'None');
  out.push(
    'Each test is tagged with its case priority, so a risk-based subset is one command:',
    '`npx playwright test --grep @high`.',
    '',
    '| Priority | Tag | Cases |',
    '| --- | --- | --: |',
    ...['High', 'Medium', 'Low']
      .filter((p) => byPriority.has(p))
      .map((p) => `| ${p} | \`@${p.toLowerCase()}\` | ${byPriority.get(p).length} |`),
    '',
  );
  for (const [doc, list] of docs) {
    out.push(`## ${doc.split('/').pop().replace(/\.md$/, '')}`, '', '| Case | Title | Priority | Automated by |', '| --- | --- | --- | --- |');
    for (const r of list) {
      const by =
        r.tests.length > 0
          ? [...new Set(r.tests.map((t) => `[${t.file.split('/').pop()}](${t.file}) (${t.project})`))].join('<br>')
          : `Manual only: ${r.manualOnly}`;
      out.push(`| [${r.id}](${r.doc}#${r.anchor}) | ${r.title.replace(/\|/g, '\\|')} | ${r.priority ?? ''} | ${by} |`);
    }
    out.push('');
  }
  return out.join('\n');
}
